# A separate R process verifies that Imports are not attached by library(fgof).
library(fgof)
stopifnot(!"package:mvtnorm" %in% search())
stopifnot(!"package:numDeriv" %in% search())
set.seed(123)
x <- rlnorm(40, 1, 0.5)
start <- list(meanlog = 1, sdlog = 0.5)
set.seed(42)
result <- gof.test(x, "lnorm", 3, start, ng = 17)
stopifnot(!"package:mvtnorm" %in% search())
stopifnot(!"package:numDeriv" %in% search())
set.seed(42)
stopifnot(identical(result, fgof::gof.test(x, "lnorm", 3, start, ng = 17)))
